def parse_dotnet_trx_results(log: str, test_spec: TestSpec) -> dict[str, str]:
    """
    Parses the TRX logs generated by the `dotnet test` command.

    Args:
        log (str): Content of the log file or stdout.
    
    Returns:
        dict: A dictionary mapping test case names to their statuses.
    """
    test_results = {}
    
    # Find all complete TRX XML blocks in the log
    matches = re.findall(r'<TestRun.*?</TestRun>', log, re.DOTALL)
    if not matches:
        return {}  # No TRX XML found
    
    # Namespace for the TRX schema
    namespace = {'trx': 'http://microsoft.com/schemas/VisualStudio/TeamTest/2010'}
    
    summary = {
        "PASSED": 0,
        "FAILED": 0,
        "SKIPPED": 0,
        "ERROR": 0
    }
    
    # Helper function to construct fully qualified name from TestDefinitions
    def get_fully_qualified_name(root, test_id):
        test_def = root.find(f".//trx:UnitTest[@id='{test_id}']", namespace)
        if test_def is not None:
            class_name = test_def.find('trx:TestMethod', namespace).get('className')
            method_name = test_def.find('trx:TestMethod', namespace).get('name')
            return f"{class_name}.{method_name}"
        return None
    
    for trx_xml in matches:
        try:
            root = ET.fromstring(trx_xml)
            
            # Gather test results from UnitTestResult elements
            results = root.findall('.//trx:UnitTestResult', namespace)
            
            for result in results:
                test_id = result.get('testId')
                outcome_str = result.get('outcome')

                if outcome_str == "Passed":
                    outcome = TestStatus.PASSED.value
                    summary["PASSED"] += 1
                elif outcome_str == "Failed":
                    outcome = TestStatus.FAILED.value
                    summary["FAILED"] += 1
                elif outcome_str == "Skipped":
                    outcome = TestStatus.SKIPPED.value
                    summary["SKIPPED"] += 1
                elif outcome_str == "Error":
                    outcome = TestStatus.ERROR.value
                    summary["ERROR"] += 1
                else:
                    outcome = TestStatus.XFAIL.value
                
                # Get the fully qualified name from TestDefinitions
                fully_qualified_name = get_fully_qualified_name(root, test_id)
                if fully_qualified_name:
                    test_results[fully_qualified_name] = outcome
        
        except ET.ParseError:
            print(f"Error parsing XML from logs. The extracted content might not be valid XML.")
            continue
    
    # Print summary
    total = sum(summary.values())
    if total > 0:
        print("\nTest Summary:")
        print(f"Total Tests: {total}")
        print(f"Passed: {summary['PASSED']} ({(summary['PASSED']/total*100):.1f}%)")
        print(f"Failed: {summary['FAILED']} ({(summary['FAILED']/total*100):.1f}%)")
        print(f"Skipped: {summary['SKIPPED']} ({(summary['SKIPPED']/total*100):.1f}%)")
        print(f"Error: {summary['ERROR']} ({(summary['ERROR']/total*100):.1f}%)")
    
    return test_results

def parse_nunit_test_results(log: str, test_spec: TestSpec) -> dict[str, str]:
    """
    Parses the NUnit XML test results from stdout.

    Args:
        log (str): The stdout content containing NUnit XML.
    
    Returns:
        dict: A dictionary mapping test case names to their statuses.
    """
    test_results = {}
    summary = {
        "passed": 0,
        "failed": 0,
        "skipped": 0,
        "error": 0
    }
    
    try:
        xml_start = log.find('<test-run')
        xml_end = log.rfind('</test-run>') + len('</test-run>')
        if xml_start == -1 or xml_end == 0:
            print("No test-run XML content found in the log")
            return test_results
        
        print("mila xml")
            
        xml_content = log[xml_start:xml_end]
        root = ET.fromstring(xml_content)
        
        for test_case in root.findall(".//test-case"):
            test_name = test_case.get('fullname')
            result = test_case.get('result', '')
            
            if result.lower() == "passed":
                outcome = TestStatus.PASSED.value
                summary["passed"] += 1
            elif result.lower() == "failed":
                outcome = TestStatus.FAILED.value
                summary["failed"] += 1
            elif result.lower() == "skipped":
                outcome = TestStatus.SKIPPED.value
                summary["skipped"] += 1
            elif result.lower() == "inconclusive":
                outcome = TestStatus.ERROR.value
                summary["error"] += 1
            else:
                outcome = TestStatus.ERROR.value
                summary["error"] += 1
            
            test_results[test_name] = outcome
    
        total = sum(summary.values())
        print("\nTest Summary:")
        print(f"Total Tests: {total}")
        print(f"Passed: {summary['passed']} ({(summary['passed']/total*100):.1f}%)")
        print(f"Failed: {summary['failed']} ({(summary['failed']/total*100):.1f}%)")
        print(f"Skipped: {summary['skipped']} ({(summary['skipped']/total*100):.1f}%)")
        print(f"Error/Inconclusive: {summary['error']} ({(summary['error']/total*100):.1f}%)")
        
    except ET.ParseError as e:
        print(f"Error parsing XML content: {str(e)}")
    except Exception as e:
        print(f"Error processing test results: {str(e)}")
        
    return test_results

